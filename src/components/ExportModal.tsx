import React, { useState } from 'react';
import { X, Download, FileText, Code, Check } from 'lucide-react';
import { PipelineResult } from '../types/pqc';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: PipelineResult;
  legacyCode: string;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  result,
  legacyCode,
}) => {
  const [copiedType, setCopiedType] = useState<string | null>(null);

  if (!isOpen) return null;

  const downloadFile = (content: string, filename: string, type: string) => {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  const generateFullDossierMarkdown = () => {
    return `# Post-Quantum Cryptography (PQC) Migration Dossier
Generated: ${new Date().toISOString()}
Compliance Framework: NIST FIPS 203 (ML-KEM) · NIST FIPS 204 (ML-DSA) · CNSA 2.0

---

## 1. Executive Summary & CBOM Audit Report
${result.audit}

---

## 2. Crypto-Agility Architecture Roadmap
${result.plan}

---

## 3. Legacy Classical Codebase (Analyzed)
\`\`\`python
${legacyCode}
\`\`\`

---

## 4. Modernized PQC-Agile Python Implementation
\`\`\`python
${result.code}
\`\`\`

---
*Generated by NIST PQC Multi-Agent Migration Pipeline*
`;
  };

  const handleDownloadDossier = () => {
    downloadFile(
      generateFullDossierMarkdown(),
      'pqc-migration-dossier.md',
      'text/markdown'
    );
  };

  const handleDownloadPython = () => {
    downloadFile(result.code, 'pqc_modern_module.py', 'text/x-python');
  };

  const handleDownloadCbomJson = () => {
    const cbomPayload = {
      bomFormat: 'CycloneDX',
      specVersion: '1.6',
      metadata: {
        timestamp: new Date().toISOString(),
        tool: 'PQC Auditor Agent',
      },
      cryptographicBillOfMaterials: result.cbom || [],
    };
    downloadFile(
      JSON.stringify(cbomPayload, null, 2),
      'cbom-quantum-inventory.json',
      'application/json'
    );
  };

  const handleCopy = async (content: string, type: string) => {
    await navigator.clipboard.writeText(content);
    setCopiedType(type);
    setTimeout(() => setCopiedType(null), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 backdrop-blur-xs p-4">
      <div className="w-full max-w-lg rounded-xl border border-zinc-800 bg-zinc-900 shadow-2xl p-5 space-y-4">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-zinc-800 pb-3">
          <div>
            <h3 className="text-base font-semibold text-zinc-100">
              Export PQC Migration Artifacts
            </h3>
            <p className="text-xs text-zinc-400 mt-0.5">
              Download verification dossiers, CBOM specifications, or code files.
            </p>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded text-zinc-400 hover:text-zinc-200 hover:bg-zinc-800 cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Export Options list */}
        <div className="space-y-3">
          {/* Option 1: Full Dossier */}
          <div className="p-3.5 rounded-lg border border-zinc-800 bg-zinc-950/80 flex items-center justify-between gap-3">
            <div className="flex items-start gap-3">
              <FileText className="w-5 h-5 text-emerald-400 shrink-0 mt-0.5" />
              <div>
                <div className="font-semibold text-sm text-zinc-100">
                  Complete Migration Dossier (.md)
                </div>
                <div className="text-xs text-zinc-400">
                  Audit report, CBOM, architecture roadmap, and code in single dossier.
                </div>
              </div>
            </div>
            <div className="flex items-center gap-1.5 shrink-0">
              <button
                onClick={() =>
                  handleCopy(generateFullDossierMarkdown(), 'dossier')
                }
                className="px-2.5 py-1.5 rounded border border-zinc-750 bg-zinc-800 hover:bg-zinc-700 text-xs text-zinc-300 cursor-pointer"
              >
                {copiedType === 'dossier' ? (
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                ) : (
                  'Copy'
                )}
              </button>
              <button
                onClick={handleDownloadDossier}
                className="p-1.5 rounded bg-emerald-500 hover:bg-emerald-400 text-zinc-950 cursor-pointer"
                title="Download Markdown"
              >
                <Download className="w-4 h-4" />
              </button>
            </div>
          </div>

          {/* Option 2: Python Module */}
          <div className="p-3.5 rounded-lg border border-zinc-800 bg-zinc-950/80 flex items-center justify-between gap-3">
            <div className="flex items-start gap-3">
              <Code className="w-5 h-5 text-cyan-400 shrink-0 mt-0.5" />
              <div>
                <div className="font-semibold text-sm text-zinc-100">
                  Modernized Python Module (.py)
                </div>
                <div className="text-xs text-zinc-400">
                  Ready-to-run Python code wrapping liboqs and classical primitives.
                </div>
              </div>
            </div>
            <div className="flex items-center gap-1.5 shrink-0">
              <button
                onClick={() => handleCopy(result.code, 'python')}
                className="px-2.5 py-1.5 rounded border border-zinc-750 bg-zinc-800 hover:bg-zinc-700 text-xs text-zinc-300 cursor-pointer"
              >
                {copiedType === 'python' ? (
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                ) : (
                  'Copy'
                )}
              </button>
              <button
                onClick={handleDownloadPython}
                className="p-1.5 rounded bg-cyan-500 hover:bg-cyan-400 text-zinc-950 cursor-pointer"
                title="Download Python"
              >
                <Download className="w-4 h-4" />
              </button>
            </div>
          </div>

          {/* Option 3: CycloneDX 1.6 CBOM */}
          <div className="p-3.5 rounded-lg border border-zinc-800 bg-zinc-950/80 flex items-center justify-between gap-3">
            <div className="flex items-start gap-3">
              <FileText className="w-5 h-5 text-amber-400 shrink-0 mt-0.5" />
              <div>
                <div className="font-semibold text-sm text-zinc-100">
                  CycloneDX 1.6 CBOM (.json)
                </div>
                <div className="text-xs text-zinc-400">
                  Machine-readable Cryptographic Bill of Materials for security pipelines.
                </div>
              </div>
            </div>
            <div className="flex items-center gap-1.5 shrink-0">
              <button
                onClick={handleDownloadCbomJson}
                className="p-1.5 rounded bg-amber-500 hover:bg-amber-400 text-zinc-950 cursor-pointer"
                title="Download CBOM JSON"
              >
                <Download className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="border-t border-zinc-800 pt-3 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded text-xs font-medium bg-zinc-800 hover:bg-zinc-750 text-zinc-200 transition-colors cursor-pointer"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
